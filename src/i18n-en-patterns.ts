// 带数字、名称的句子：整句匹配（^…$），第二个参数用来继续翻译括号里的内容。
export type Tr = (text: string) => string
export const enPatterns: [RegExp, (m: RegExpMatchArray, tr: Tr) => string][] = [
  // 时间范围
  [/^近(\d+)天$/, m => m[1] === '1' ? 'Last 1 day' : `Last ${m[1]} days`],
  [/^近(\d+)年$/, m => m[1] === '1' ? 'Last year' : `Last ${m[1]} years`],
  [/^(\d+)天净资产曲线$/, m => `${m[1]}-day net worth curve`],
  [/^当前为(.+)$/, (m, tr) => `current: ${tr(m[1])}`],
  [/^(.+)账户卡片$/, m => `${m[1]} account card`],
  [/^(.+?)图标占位$/, (m, tr) => `${tr(m[1])} icon placeholder`],
  [/^(.+?)图标$/, (m, tr) => `${tr(m[1])} icon`],
  // 数量
  [/^(\d+) 笔持仓$/, m => `${m[1]} positions`],
  [/^(\d+) 项资产$/, m => `${m[1]} assets`],
  [/^(\d+) 笔合约$/, m => `${m[1]} contracts`],
  [/^(\d+) 笔$/, m => `${m[1]} items`],
  [/^(\d+) 项$/, m => `${m[1]} items`],
  [/^还有 (\d+) 项资产$/, m => `${m[1]} more assets`],
  [/^展开全部 (\d+) 项$/, m => `Show all ${m[1]} items`],
  [/^占(支出|收入|亏损|盈利) (.+)$/, m => `${m[2]} of ${{ 支出: 'expenses', 收入: 'income', 亏损: 'losses', 盈利: 'profits' }[m[1]]}`],
  [/^(\d+) 美元 = ([\d.]+) 人民币$/, m => `${m[1]} USD = ${m[2]} CNY`],
  [/^(.+) 全仓$/, m => `${m[1]} cross`],
  [/^(.+) 逐仓$/, m => `${m[1]} isolated`],
  // 操作和提示
  [/^查看(.+?)持仓详情$/, (m, tr) => `View ${tr(m[1])} holding details`],
  [/^查看(.+?)这一轮合约详情$/, (m, tr) => `View this ${tr(m[1])} contract round`],
  [/^查看(.+?)奖励详情$/, (m, tr) => `View ${tr(m[1])} reward details`],
  [/^查看(.+?)账户详情$/, (m, tr) => `View ${tr(m[1])} account details`],
  [/^查看(.+?)资产明细$/, (m, tr) => `View ${tr(m[1])} asset details`],
  [/^查看 ?(.+?) ?详情$/, (m, tr) => `View ${tr(m[1])} details`],
  [/^打开 ?(.+?) ?详情$/, (m, tr) => `Open ${tr(m[1])} details`],
  [/^(\S+) (做多|做空) (.+)$/, (m, tr) => `${m[1]} ${tr(m[2])} ${tr(m[3])}`],
  [/^刷新([^，。：；]+)$/, m => `Refresh ${m[1]}`],
  [/^修改([^，。：；]+)$/, m => `Edit ${m[1]}`],
  [/^移除([^，。：；]+)$/, m => `Remove ${m[1]}`],
  [/^复制([^，。：；]+)$/, m => `Copy ${m[1]}`],
  [/^查看原因：(.*)$/, (m, tr) => `View reason: ${tr(m[1])}`],
  [/^最近成功：(.+)$/, m => `Last success: ${m[1]}`],
  [/^查看(.+?)在当前账户中的详情$/, (m, tr) => `View ${tr(m[1])} details in this account`],
  [/^行情时间：(.+)$/, m => `Quote time: ${m[1]}`],
  [/^平仓 (.+)$/, m => `Closed ${m[1]}`],
  [/^自动行情 · (.+)$/, m => `Auto price · ${m[1]}`],
  [/^更新于 (.+)$/, m => `Updated ${m[1]}`],
  [/^U本位合约 ([A-Z0-9]+)$/, m => `USDⓈ-M futures ${m[1]}`],
  [/^U本位资金费历史（(.+)）$/, (m, tr) => `USDⓈ-M funding history (${tr(m[1])})`],
  [/^近(\d+)个月$/, m => `last ${m[1]} months`],
  [/^本次账户尚未更新成功，显示上次成功读取的止盈止损（(.+)）。委托可能已有变化，等待重新读取确认。$/, m => `This account has not refreshed yet; showing the last successfully loaded take-profit / stop-loss (${m[1]}). Orders may have changed; waiting for the next refresh.`],
  [/^(?:(\d+)天 )?(?:(\d+)小时 )?(\d+)分钟$/, m => [m[1] && `${m[1]}d`, m[2] && `${m[2]}h`, `${m[3]}m`].filter(Boolean).join(' ')],
  [/^更换(.+?)图标，最大 1 MB$/, (m, tr) => `Replace ${tr(m[1])} icon, max 1 MB`],
  [/^填写正数，例如(\d+)$/, m => `Enter a positive number, e.g. ${m[1]}`],
  [/^结清(.+)$/, (m, tr) => `Settle ${tr(m[1])}`],
  [/^这个网络地址连续输错 5 次，已锁定 (\d+) 小时。请在服务器上运行 sudo investment-unlock 解除。$/, m => `Five wrong codes in a row from this network address; locked for ${m[1]} hours. Run sudo investment-unlock on the server to unlock.`],
  [/^平台返回的交易资料无法核对（(.+)），本范围未读全，已保留旧记录。$/, (m, tr) => `The trade data returned by the platform could not be verified (${tr(m[1])}); this range is not fully loaded and the old records are kept.`],
  [/^(.+?) 本批有(\d+)条未通过，合法记录已保留。$/, (m, tr) => `${tr(m[1])} ${m[2]} in this batch failed; valid records are kept.`],
  [/^有(\d+)笔奖励缺少对应历史价格，暂不计入USDT合计，原始记录保留；后续自动更新继续补齐。$/, m => `${m[1]} rewards lack a historical price and are not counted in the USDT total; the original records are kept and will be completed by later automatic updates.`],
  [/^本机资料库无法读取，已暂停修改。(.+)$/, (m, tr) => `The local database cannot be read; changes are paused. ${tr(m[1])}`],
  [/^(.+?)·$/, (m, tr) => `${tr(m[1].trim())} ·`],
]
